<script>
const plantillasLeccion = @json($plantillasLeccion);

document.addEventListener('DOMContentLoaded', function() {
    const plantillaSelect = document.getElementById('plantilla_leccion');
    const tituloInput = document.getElementById('titulo');
    const contenidoTextarea = document.getElementById('contenido');
    const duracionInput = document.getElementById('duracion_minutos');

    plantillaSelect.addEventListener('change', function() {
        const clave = this.value;

        if (!plantillasLeccion[clave]) {
            return;
        }

        const plantilla = plantillasLeccion[clave];

        tituloInput.value = plantilla.titulo;
        contenidoTextarea.value = plantilla.contenido;
        duracionInput.value = plantilla.duracion_minutos;
    });
});
